/**
 * Helper to fetch translation with fallback
 */
export function getTranslation(key: keyof TranslationSet, customLang?: string): string {
  const lang = (customLang || localStorage.getItem("math_game_language") || "en") as LanguageCode;
  const currentSet = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return currentSet[key] || TRANSLATIONS.en[key] || String(key);
}

/**
 * Returns current language code
 */
export function getCurrentLanguage(): LanguageCode {
  return (localStorage.getItem("math_game_language") || "en") as LanguageCode;
}
